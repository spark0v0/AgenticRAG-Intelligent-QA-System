import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'
import { format, resolveConfig } from 'prettier'

const root = fileURLToPath(new URL('../../', import.meta.url))
const local = fileURLToPath(new URL(process.platform === 'win32' ? '../../.venv/Scripts/python.exe' : '../../.venv/bin/python', import.meta.url))
const python = process.env.WORKBENCH_PYTHON || (existsSync(local) ? local : 'python')
const schema = JSON.parse(execFileSync(python, ['scripts/export_api_schema.py'], { cwd: root, encoding: 'utf8' }))
const target = fileURLToPath(new URL('../src/types/api.generated.ts', import.meta.url))
const output = await format('/** Generated by npm run api:generate. Do not edit. */\n' + astToString(await openapiTS(schema)), { ...await resolveConfig(target), parser: 'typescript' })
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== output) {
    console.error('API types differ from FastAPI. Run npm run api:generate.')
    process.exitCode = 1
  }
} else writeFileSync(target, output)
