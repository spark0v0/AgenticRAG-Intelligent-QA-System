import { test, expect } from '@playwright/test'
import { resolve } from 'node:path'

test('MCP configuration, discovery, schema trial, activation and narrow layout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/tools')
  await page.getByRole('button', { name: '添加服务', exact: true }).click()
  let dialog = page.getByRole('dialog')
  await dialog.getByLabel('服务名称').fill('离线查询服务')
  await dialog.getByLabel('连接方式').selectOption('stdio')
  await dialog.getByLabel('可执行程序').fill(process.env.WORKBENCH_PYTHON || 'python')
  await dialog.getByLabel('启动参数（JSON 数组）').fill(JSON.stringify([resolve('../tests/mcp_fixture.py')]))
  await dialog.getByRole('button', { name: '保存配置' }).click()
  await expect(dialog).not.toBeVisible()
  const card = page.locator('.mcp-service').filter({ hasText: '离线查询服务' })
  await expect(card.getByText('尚未连接', { exact: true })).toBeVisible()
  await card.getByRole('button', { name: '连接并发现' }).click()
  await expect(card.getByText('连接已验证', { exact: true })).toBeVisible()
  const tool = card.locator('.mcp-tool-row').filter({ hasText: 'city_info' })
  await tool.getByRole('checkbox').check()
  await expect(card.locator('.mcp-tool-row').filter({ hasText: 'unspecified_action' }).getByRole('checkbox')).toBeDisabled()
  await tool.getByRole('button', { name: '试运行' }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: '执行查询' }).click()
  await expect(dialog.getByText('工具参数不符合 Schema，请检查必填字段、类型与取值范围')).toBeVisible()
  await dialog.getByLabel('调用参数（JSON 对象）').fill('{"city":"西安","days":2}')
  await dialog.getByRole('button', { name: '执行查询' }).click()
  await expect(dialog.locator('.mcp-result')).toContainText('测试城市：西安；天数：2')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(card.locator('.mcp-call-status')).toContainText('city_info · 成功')
  await expect(tool.getByRole('checkbox')).toBeChecked()
  await card.getByRole('button', { name: '应用到问答' }).click()
  await expect(card.getByText('1 个工具已启用', { exact: true })).toBeVisible()
  await page.reload()
  await expect(card.getByText('1 个工具已启用', { exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/tools-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/tools-mobile.png', fullPage: true })
  await page.getByRole('button', { name: /切换(?:深色|浅色)主题/ }).click()
  await page.screenshot({ path: 'test-results/tools-mobile-dark.png', fullPage: true, animations: 'disabled' })
  await card.getByRole('button', { name: '停用', exact: true }).click()
  await expect(card.getByText('未用于问答', { exact: true })).toBeVisible()
  await card.getByRole('button', { name: '编辑', exact: true }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByLabel('服务名称').fill('修改后的离线服务')
  await dialog.getByRole('button', { name: '保存配置' }).click()
  await expect(page.locator('.mcp-service').getByText('尚未连接', { exact: true })).toBeVisible()
  await page.locator('.mcp-service').getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '删除配置', exact: true }).click()
  await expect(page.getByText('连接你的第一个工具服务')).toBeVisible()
  expect(errors).toEqual([])
})
